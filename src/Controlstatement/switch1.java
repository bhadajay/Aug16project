package Controlstatement;

public class switch1 {
	
	
	
	public static void main(String[] args) {
		
		switch(3)
		{
		
		case(1) : System.out.println("Print case1 ");
		break ;
		
		case(2) : System.out.println("Print case2 ");
		break ;
		
		case(3) : System.out.println("Print case 3 ");
		break ;
		
		
		}
		
	}

}
